#include <windows.h>
#include <sddl.h>
#include <stdio.h>
#include <string>

#include <openssl/bn.h>
#include <openssl/err.h>
#include <openssl/pem.h>
#include <openssl/rand.h>
#include <openssl/x509v3.h>

static bool AddExtension( X509 *pCertificate, int nid, const char *pValue )
{
	X509V3_CTX context;
	X509V3_set_ctx( &context, pCertificate, pCertificate, NULL, NULL, 0 );
	X509_EXTENSION *pExtension = X509V3_EXT_conf_nid( NULL, &context, nid, pValue );
	bool result = pExtension && X509_add_ext( pCertificate, pExtension, -1 ) == 1;
	X509_EXTENSION_free( pExtension );
	return result;
}

static bool WriteNewFile( const char *pPath, BIO *pContent, const char *pComment, bool privateFile )
{
	PSECURITY_DESCRIPTOR pDescriptor = NULL;
	SECURITY_ATTRIBUTES attributes = { sizeof( attributes ), NULL, FALSE };
	if ( privateFile )
	{
		if ( !ConvertStringSecurityDescriptorToSecurityDescriptorA(
			"D:P(A;;FA;;;SY)(A;;FA;;;OW)", SDDL_REVISION_1, &pDescriptor, NULL ) )
		{
			return false;
		}
		attributes.lpSecurityDescriptor = pDescriptor;
	}
	HANDLE file = CreateFileA( pPath, GENERIC_WRITE, 0,
		privateFile ? &attributes : NULL, CREATE_NEW, FILE_ATTRIBUTE_NORMAL, NULL );
	LocalFree( pDescriptor );
	if ( file == INVALID_HANDLE_VALUE )
	{
		return false;
	}
	char *pData = NULL;
	long length = BIO_get_mem_data( pContent, &pData );
	std::string content = pComment;
	content.append( pData, length );
	DWORD written = 0;
	bool result = WriteFile( file, content.data(), static_cast< DWORD >( content.size() ), &written, NULL ) &&
		written == content.size() && FlushFileBuffers( file );
	CloseHandle( file );
	return result;
}

int main( int argc, char *argv[] )
{
	if ( argc != 3 )
	{
		fprintf( stderr, "Usage: CreateLocalIdentity.exe certificate.pem private-key.pem\n" );
		return 2;
	}
	if ( GetFileAttributesA( argv[1] ) != INVALID_FILE_ATTRIBUTES ||
		GetFileAttributesA( argv[2] ) != INVALID_FILE_ATTRIBUTES )
	{
		fprintf( stderr, "An identity file already exists. Refusing to rotate or overwrite it.\n" );
		return 3;
	}

	OPENSSL_init_crypto( OPENSSL_INIT_NO_LOAD_CONFIG, NULL );
	EVP_PKEY *pKey = EVP_PKEY_Q_keygen( NULL, NULL, "RSA", 3072 );
	X509 *pCertificate = X509_new();
	BIO *pCertificateOutput = BIO_new( BIO_s_mem() );
	BIO *pKeyOutput = BIO_new( BIO_s_mem() );
	unsigned char serial[16] = { 0 };
	bool result = pKey && pCertificate && pCertificateOutput && pKeyOutput &&
		RAND_bytes( serial, sizeof( serial ) ) == 1;
	serial[0] = ( serial[0] & 0x7f ) | 1;
	BIGNUM *pSerial = BN_bin2bn( serial, sizeof( serial ), NULL );
	if ( result )
	{
		X509_NAME *pName = X509_get_subject_name( pCertificate );
		result = pSerial && X509_set_version( pCertificate, 2 ) == 1 &&
			BN_to_ASN1_INTEGER( pSerial, X509_get_serialNumber( pCertificate ) ) &&
			X509_gmtime_adj( X509_getm_notBefore( pCertificate ), -300 ) &&
			X509_gmtime_adj( X509_getm_notAfter( pCertificate ), 31536000 ) &&
			X509_set_pubkey( pCertificate, pKey ) == 1 &&
			X509_NAME_add_entry_by_txt( pName, "CN", MBSTRING_ASC,
				reinterpret_cast< const unsigned char * >( "Jx Local Test Server" ), -1, -1, 0 ) == 1 &&
			X509_NAME_add_entry_by_txt( pName, "OU", MBSTRING_ASC,
				reinterpret_cast< const unsigned char * >( "Private development identity" ), -1, -1, 0 ) == 1 &&
			X509_set_issuer_name( pCertificate, pName ) == 1 &&
			AddExtension( pCertificate, NID_basic_constraints, "critical,CA:TRUE,pathlen:0" ) &&
			AddExtension( pCertificate, NID_key_usage,
				"critical,digitalSignature,keyEncipherment,keyCertSign,cRLSign" ) &&
			AddExtension( pCertificate, NID_ext_key_usage, "serverAuth" ) &&
			AddExtension( pCertificate, NID_subject_alt_name,
				"DNS:localhost,IP:127.0.0.1,DNS:fs.seayoo.com" ) &&
			AddExtension( pCertificate, NID_subject_key_identifier, "hash" ) &&
			AddExtension( pCertificate, NID_authority_key_identifier, "keyid:always" ) &&
			X509_sign( pCertificate, pKey, EVP_sha256() ) > 0 &&
			X509_check_private_key( pCertificate, pKey ) == 1 &&
			PEM_write_bio_X509( pCertificateOutput, pCertificate ) == 1 &&
			PEM_write_bio_PrivateKey( pKeyOutput, pKey, NULL, NULL, 0, NULL, NULL ) == 1;
	}
	if ( result )
	{
		const char *pCertificateComment =
			"# Local development TLS certificate, generated by Sources/S3Tools/ClientTls/CreateLocalIdentity.cpp.\n"
			"# Approved in the local TLS adaptation task for the independent Release/Client test client.\n"
			"# Heaven reads this file and server-key.pem from Resources/ServerConfig/ClientTls.\n"
			"# Bishop and GameServer load the same identity at startup; restart both to apply changes.\n"
			"# fs.seayoo.com is the client's fixed TLS name, not a claim to official server ownership.\n"
			"# PatchClientTrust embeds only this public certificate in the independent client.\n"
			"# Regeneration requires redeploying that client public trust and restarting services.\n"
			"# Keep this file paired with the private key. Never overwrite a working pair casually.\n";
		const char *pKeyComment =
			"# PRIVATE local development TLS key. DO NOT COPY TO CLIENT, LOGS, OR GIT.\n"
			"# Generated by Sources/S3Tools/ClientTls/CreateLocalIdentity.cpp with a random RSA-3072 key.\n"
			"# Permissions are restricted to the file owner and SYSTEM. See DevDoc for approval and changes.\n"
			"# Heaven loads this key with server-cert.pem from this directory at service startup.\n"
			"# Restart Bishop and GameServer after an approved identity change.\n"
			"# To rotate: stop services, preserve this pair, generate a fresh pair with CreateLocalIdentity,\n"
			"# then use PatchClientTrust with the new public certificate and restart services.\n"
			"# Never use an official server key or upload this file.\n";
		result = WriteNewFile( argv[2], pKeyOutput, pKeyComment, true ) &&
			WriteNewFile( argv[1], pCertificateOutput, pCertificateComment, false );
	}
	if ( result )
	{
		unsigned char digest[EVP_MAX_MD_SIZE] = { 0 };
		unsigned int length = 0;
		X509_digest( pCertificate, EVP_sha256(), digest, &length );
		printf( "Local certificate SHA256: " );
		for ( unsigned int i = 0; i < length; ++i )
		{
			printf( "%02X", digest[i] );
		}
		printf( "\nThe existing identity was not overwritten.\n" );
	}
	else
	{
		fprintf( stderr, "Identity generation failed. Check destination permissions and incomplete files.\n" );
		ERR_print_errors_fp( stderr );
	}
	BN_free( pSerial );
	BIO_free( pKeyOutput );
	BIO_free( pCertificateOutput );
	X509_free( pCertificate );
	EVP_PKEY_free( pKey );
	return result ? 0 : 1;
}
